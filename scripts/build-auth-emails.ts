// Writes the email templates kept outside the app from lib/email-layout.ts:
// - supabase/templates/{confirmation,recovery}.html for Supabase Auth (upload them in
//   Auth > Email Templates or through the Management API)
// - supabase/templates/notification-emails.sql, the upsert for the emails the database sends
// Run: node --experimental-strip-types scripts/build-auth-emails.ts
import { writeFileSync } from 'node:fs'
import { AUTH_EMAILS, NOTIFICATION_EMAILS } from '../lib/email-layout.ts'

for (const [name, { subject, html }] of Object.entries(AUTH_EMAILS)) {
  writeFileSync(`supabase/templates/${name}.html`, html + '\n')
  console.log(`${name}: ${subject}`)
}

const literal = (text: string) => `$tpl$${text}$tpl$`
const rows = Object.entries(NOTIFICATION_EMAILS)
  .map(([name, { subject, html }]) => `  (${literal(name)}, ${literal(subject)}, ${literal(html)})`)
  .join(',\n')
writeFileSync(
  'supabase/templates/notification-emails.sql',
  `-- Generated by scripts/build-auth-emails.ts. Do not edit by hand.\n` +
    `INSERT INTO email_templates (name, subject, html) VALUES\n${rows}\n` +
    `ON CONFLICT (name) DO UPDATE SET subject = EXCLUDED.subject, html = EXCLUDED.html;\n`
)
console.log('notification-emails.sql:', Object.keys(NOTIFICATION_EMAILS).join(', '))
